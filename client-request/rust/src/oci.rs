use oci_client::manifest::OciImageManifest;
use oci_client::Reference;
use std::collections::BTreeSet;

/// Builds the blob URL for the given registry, repository and digest.
pub(crate) fn build_blob_url(registry: &str, repository: &str, digest: &str) -> String {
    format!("https://{registry}/v2/{repository}/blobs/{digest}")
}

/// Builds the manifest URL for the given registry, repository and reference (tag or
/// digest).
pub(crate) fn build_manifest_url(registry: &str, repository: &str, reference: &str) -> String {
    format!("https://{registry}/v2/{repository}/manifests/{reference}")
}

/// Collects the distinct digests of the config and the layers of the manifest in
/// sorted order, so a blob referenced from several layers yields one task.
pub(crate) fn blob_digests(manifest: &OciImageManifest) -> BTreeSet<&str> {
    std::iter::once(manifest.config.digest.as_str())
        .chain(manifest.layers.iter().map(|layer| layer.digest.as_str()))
        .collect()
}

/// Resolves the registry host of the image reference. The docker.io registry is
/// resolved to registry-1.docker.io, aligned with the OCI resolver in the
/// dragonfly, so that the urls are identical to the ones generated by the Go
/// implementation.
pub(crate) fn resolve_registry(reference: &Reference) -> &str {
    match reference.registry() {
        "docker.io" => "registry-1.docker.io",
        registry => registry,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use oci_client::manifest::OciDescriptor;

    #[test]
    fn build_blob_url_uses_https_by_default() {
        let url = build_blob_url("registry.example.com", "library/nginx", "sha256:abcdef");

        assert_eq!(
            url,
            "https://registry.example.com/v2/library/nginx/blobs/sha256:abcdef"
        );
    }

    #[test]
    fn build_manifest_url_uses_https_by_default() {
        let url = build_manifest_url("registry.example.com", "library/nginx", "latest");

        assert_eq!(
            url,
            "https://registry.example.com/v2/library/nginx/manifests/latest"
        );
    }

    #[test]
    fn blob_digests_dedupes_the_config_and_layers() {
        let descriptor = |digest: &str| OciDescriptor {
            digest: digest.to_string(),
            ..Default::default()
        };
        let manifest = OciImageManifest {
            config: descriptor("sha256:cccc"),
            layers: vec![
                descriptor("sha256:bbbb"),
                descriptor("sha256:aaaa"),
                descriptor("sha256:bbbb"),
                descriptor("sha256:cccc"),
            ],
            ..Default::default()
        };

        assert_eq!(
            blob_digests(&manifest).into_iter().collect::<Vec<_>>(),
            vec!["sha256:aaaa", "sha256:bbbb", "sha256:cccc"]
        );
    }

    #[test]
    fn resolve_registry_maps_docker_hub() {
        let test_cases = vec![
            ("nginx", "registry-1.docker.io"),
            ("example.com/foo/bar:1.0", "example.com"),
        ];

        for (image, expected) in test_cases {
            let reference: Reference = image.parse().unwrap();
            assert_eq!(resolve_registry(&reference), expected);
        }
    }
}
